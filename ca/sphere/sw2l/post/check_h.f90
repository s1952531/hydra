!######################################################################
!  Tests the inversion of h, assuming all other fields are fixed.

!  The required data are first generated by init/random_huv.f90.
!######################################################################

program checkh

 !Import spectral module, constants and parameters:
use spectral

implicit none

 !Local parameters and variables:
double precision,parameter:: tole=1.d-12
 !tole: relative error in successive iterates when finding h_1 & h_2.
 !      The error norm is 
 !      <c_1^2*dh_1^2> + (rho_2/rho_1)*(H_2/H_1)*<c_2^2*dh_2^2>
 !      where <:> means a horizontal domain average and dh_j is
 !      the difference from the previous guess.

 !Physical fields:
double precision:: h1(numLatGridPts,numLongGridPts),h2(numLatGridPts,numLongGridPts)
double precision:: u1(numLatGridPts,numLongGridPts),u2(numLatGridPts,numLongGridPts)
double precision:: z1(numLatGridPts,numLongGridPts),z2(numLatGridPts,numLongGridPts)
double precision:: g1(numLatGridPts,numLongGridPts),g2(numLatGridPts,numLongGridPts)

!For computing error from input fields:
double precision:: h1i(numLatGridPts,numLongGridPts),h2i(numLatGridPts,numLongGridPts)

 !Mode values of h1 & h2:
double precision:: h1m(numLatGridPts,numLongGridPts),h2m(numLatGridPts,numLongGridPts)

 !Other:
double precision:: h1o(numLatGridPts,numLongGridPts),h2o(numLatGridPts,numLongGridPts)
double precision:: fs1(numLatGridPts,numLongGridPts),fs2(numLatGridPts,numLongGridPts)

double precision:: wka(numLatGridPts,numLongGridPts),wkb(numLatGridPts,numLongGridPts)
double precision:: rhs(numLatGridPts)
double precision:: t,hnorm,avg
double precision:: wgt,wgtc
integer:: i,m,iopt

 !---------------------------------------------------------------------
 !Initialise inversion constants and arrays:
call init_spectral

write(*,*) ' Enter the relaxation parameter < 1:'
read(*,*) wgt
wgtc = one-wgt

!----------------------------------------------------------------------
 !Read h:
open(11, file = 'hh0_init.r8', form = 'unformatted', &
      access = 'direct', status = 'old', recl = 2*nbytes)
read(11,rec=1) t, h1
read(11,rec=2) t, h2
close(11)

 !Ensure domain average is zero:
call zeroavg(h1)
call zeroavg(h2)

 !Keep copies for computing differences below:
h1i = h1
h2i = h2

!----------------------------------------------------------------------
 !Read u:
open(11, file = 'uu0_init.r8', form = 'unformatted', &
      access = 'direct', status = 'old', recl = 2*nbytes)
read(11,rec=1) t, u1
read(11,rec=2) t, u2
close(11)

!----------------------------------------------------------------------
 !Read zeta:
open(11, file = 'zz0_init.r8', form = 'unformatted', &
      access = 'direct', status = 'old', recl = 2*nbytes)
read(11,rec=1) t, z1
read(11,rec=2) t, z2
close(11)

 !Ensure domain average is zero:
call zeroavg(z1)
call zeroavg(z2)

!----------------------------------------------------------------------
 !Read gamma:
open(11, file = 'gg0_init.r8', form = 'unformatted', &
      access = 'direct', status = 'old', recl = 2*nbytes)
read(11,rec=1) t, g1
read(11,rec=2) t, g2
close(11)

!----------------------------------------------------------------------
write(*,*) ' Start with (1) h = 0 or (2) the exact solution?'
read(*,*) iopt

if (iopt == 1) then
   h1 = zero
   h2 = zero
endif
 !Otherwise, we start from the actual solution.

 !Compute fixed parts of the source terms needed to invert h:
do i=1,numLongGridPts
  fs1(:,i)=g1(:,i)+bet*u1(:,i)-cof*z1(:,i)
  fs2(:,i)=g2(:,i)+bet*u2(:,i)-cof*z2(:,i)
enddo

 !Convert to semi-spectral space:
call forfft(numLatGridPts,numLongGridPts,fs1,trig,factors)
call forfft(numLatGridPts,numLongGridPts,fs2,trig,factors)

 !Remove global mean values:
rhs=fs1(:,1)*clat
avg=(f1112*(rhs(1)+rhs(numLatGridPts))+sum(rhs(2:ngm1)))*rsumi
fs1(:,1)=fs1(:,1)-avg

rhs=fs2(:,1)*clat
avg=(f1112*(rhs(1)+rhs(numLatGridPts))+sum(rhs(2:ngm1)))*rsumi
fs2(:,1)=fs2(:,1)-avg

!>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>
 !Iterate to find h1 & h2, with all other quantities fixed:
hnorm=one
do while (hnorm > tole)
   !Save previous fields to be able to compute error below:
  h1o=h1
  h2o=h2

   !Convert h1 & h2 to semi-spectral space:
  call forfft(numLatGridPts,numLongGridPts,h1,trig,factors)
  call forfft(numLatGridPts,numLongGridPts,h2,trig,factors)

   !Complete calculation of the source terms:
  do m=1,numLongGridPts
    h1(:,m)=fs1(:,m)+fsq*h1(:,m)
    h2(:,m)=fs2(:,m)+fsq*h2(:,m)
  enddo
   !fsq = f^2 above.

   !-------------------------------------------------------------------
   !Solve for h1 & h2 in mode space, where the equations are decoupled.

   !Mode 1:
  wka=h1*vm11+h2*vm12
  call helm1(wka,h1m,wkb)
   !Solves f^2*h_1 - \tilde{c}_1^2*Lap(h_1) = wka, where h_1 is h for mode 1
   !The solution is stored in h1m.
  
   !Mode 2:
  wka=h1*vm21+h2*vm22
  call helm2(wka,h2m,wkb)
   !Solves f^2*h_2 - \tilde{c}_2^2*Lap(h_2) = wka, where h_2 is h for mode 2
   !The solution is stored in h2m.

   !Return h1 & h2 to layers as semi-spectral arrays, then physical ones:
  h1=h1m*vt11+h2m*vt12
  call revfft(numLatGridPts,numLongGridPts,h1,trig,factors) 
  h2=h1m*vt21+h2m*vt22
  call revfft(numLatGridPts,numLongGridPts,h2,trig,factors) 

   !Compute relative rms error:
  wka=csq1*(h1-h1o)**2+mubar*csq2*(h2-h2o)**2
  wkb=csq1*h1**2+mubar*csq2*h2**2
  hnorm=average(wka)/(average(wkb)+small)
   !Small = 1.d-12 is added to avoid dividing by zero for a rest state

   !Employ relaxation to improve convergence:
  h1=wgt*h1+wgtc*h1o
  h2=wgt*h2+wgtc*h2o

  if (hnorm > one) stop
enddo
!<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<
 !Passing this point, we have converged!

wka = abs(h1-h1i)
wkb = abs(h1i)
write(*,*) ' Max abs relative error in h1 = ',maxval(wka)/maxval(wkb)

wka = abs(h2-h2i)
wkb = abs(h2i)
write(*,*) ' Max abs relative error in h2 = ',maxval(wka)/maxval(wkb)

!------------------------------------------------------------------
 !Save h:
open(11,file='hh_init.r8',form='unformatted', &
      access='direct',status='replace',recl=2*nbytes)
write(11,rec=1) zero,h1
write(11,rec=2) zero,h2
close(11)

end program checkh
