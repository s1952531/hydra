!######################################################################
!  Tests the inversion of q, delta & gamma to recover h, u & v.

!  Here, we reproduce main_invert in the spectral module so it
!  can be checked at each step in the procedure.

!  Data are first generated by init/random_huv.f90. Uses the actual
!  solution as a first guess.
!######################################################################

program checkinv

 !Import spectral module, constants and parameters:
use spectral

implicit none

 !Local parameters and variables:
double precision,parameter:: tole=1.d-12
 !tole: relative energy norm error in successive iterates when finding
 !      hj, uj & vj from qj, dj & gj (for j = 1 & 2).  The energy norm is
 !      <du1^2+dv1^2+c_1^2*dh1^2> + (rho_2/rho_1)*(H_2/H_1)*
 !      <du2^2+dv2^2+c_2^2*dh2^2>
 !      where <:> means a horizontal domain average and (duj,dvj,dhj)
 !      is either the current guess for (uj,vj,hj) or the difference
 !      from the previous guess.

double precision,parameter:: wgt=0.5d0, wgtc=1.d0-wgt
 !wgt: relaxation parameter used to speed convergence (wgt near 1 fails)

 !Physical fields:
double precision:: q1(ng,nt),q2(ng,nt)
double precision:: d1(ng,nt),d2(ng,nt)
double precision:: g1(ng,nt),g2(ng,nt)
double precision:: h1(ng,nt),h2(ng,nt)
double precision:: u1(ng,nt),u2(ng,nt)
double precision:: v1(ng,nt),v2(ng,nt)
double precision:: z1(ng,nt),z2(ng,nt)

!Copies of h, u & v to compute differences from input fields:
double precision:: h1i(ng,nt),h2i(ng,nt)
double precision:: u1i(ng,nt),u2i(ng,nt)
double precision:: v1i(ng,nt),v2i(ng,nt)
double precision:: z1i(ng,nt),z2i(ng,nt)

 !Semi-spectral fields:
double precision:: ds1(ng,nt),ds2(ng,nt)
double precision:: gs1(ng,nt),gs2(ng,nt)

 !Mode values of h1 & h2:
double precision:: h1m(ng,nt),h2m(ng,nt)

 !Other:
double precision:: h1o(ng,nt),h2o(ng,nt)
double precision:: u1o(ng,nt),u2o(ng,nt)
double precision:: v1o(ng,nt),v2o(ng,nt)

double precision:: ud1(ng,nt),ud2(ng,nt)
double precision:: vd1(ng,nt),vd2(ng,nt)

double precision:: wka(ng,nt),wkb(ng,nt),wkc(ng,nt)
double precision:: t,enorm
integer:: i,m,iopt

 !---------------------------------------------------------------------
 !Initialise inversion constants and arrays:
call init_spectral

!----------------------------------------------------------------------
 !Read in the total PV, (zeta+f)/(1+h), where zeta is the relative
 !vorticity and h is the dimensionless height anomaly in each layer:
open(11, file = 'qq_init.r8', form = 'unformatted', &
      access = 'direct', status = 'old', recl = 2*nbytes)
read(11,rec=1) t, q1
read(11,rec=2) t, q2
close(11)

!----------------------------------------------------------------------
 !Read h:
open(11, file = 'hh0_init.r8', form = 'unformatted', &
      access = 'direct', status = 'old', recl = 2*nbytes)
read(11,rec=1) t, h1
read(11,rec=2) t, h2
close(11)
 !Keep copies for computing differences below:
h1i = h1
h2i = h2

!----------------------------------------------------------------------
 !Read u:
open(11, file = 'uu0_init.r8', form = 'unformatted', &
      access = 'direct', status = 'old', recl = 2*nbytes)
read(11,rec=1) t, u1
read(11,rec=2) t, u2
close(11)
 !Keep copies for computing differences below:
u1i = u1
u2i = u2

!----------------------------------------------------------------------
 !Read v:
open(11, file = 'vv0_init.r8', form = 'unformatted', &
      access = 'direct', status = 'old', recl = 2*nbytes)
read(11,rec=1) t, v1
read(11,rec=2) t, v2
close(11)
 !Keep copies for computing differences below:
v1i = v1
v2i = v2

!----------------------------------------------------------------------
 !Read zeta:
open(11, file = 'zz0_init.r8', form = 'unformatted', &
      access = 'direct', status = 'old', recl = 2*nbytes)
read(11,rec=1) t, z1
read(11,rec=2) t, z2
close(11)
 !Keep copies for computing differences below:
z1i = z1
z2i = z2

!----------------------------------------------------------------------
 !Read in divergence, ds:
open(11, file = 'dd0_init.r8', form = 'unformatted', &
      access = 'direct', status = 'old', recl = 2*nbytes)
read(11,rec=1) t, ds1
read(11,rec=2) t, ds2
close(11)

 !Ensure domain average is zero:
call zeroavg(ds1)
call zeroavg(ds2)

 !Convert to semi-spectral space as ds:
call forfft(ng,nt,ds1,trig,factors) 
call forfft(ng,nt,ds2,trig,factors) 

!----------------------------------------------------------------------
 !Read in acceleration divergence, gs:
open(11, file = 'gg0_init.r8', form = 'unformatted', &
      access = 'direct', status = 'old', recl = 2*nbytes)
read(11,rec=1) t, gs1
read(11,rec=2) t, gs2
close(11)

 !Ensure domain average is zero:
call zeroavg(gs1)
call zeroavg(gs2)

 !Convert to semi-spectral space as gs:
call forfft(ng,nt,gs1,trig,factors) 
call forfft(ng,nt,gs2,trig,factors) 

!----------------------------------------------------------------------
write(*,*) ' Start with (1) h = u = v = 0, or (2) the exact solution?'
read(*,*) iopt

if (iopt == 1) then
   h1 = zero
   h2 = zero
   u1 = zero
   u2 = zero
   v1 = zero
   v2 = zero
endif
 !Otherwise, we start from the actual solution.

 !Invert q, delta and gamma to recover h, u & v:

 !First compute divergent part of the velocity field (this is fixed
 !in the iteration below):

 !Invert Laplace's operator on the divergence (ds) in both layers:
call laplinv(ds1,wka,vd1)
call laplinv(ds2,wkb,vd2)
 !Here the divergence potential is wka or wkb, and its latitudinal
 !derivative is vd1 or vd2, the divergent meridional velocity
 !(all in semi-spectral space)

 !Compute divergent zonal velocity ud in both layers:
call deriv(ng,nt,rk,wka,ud1) 
call deriv(ng,nt,rk,wkb,ud2) 
do m=1,nt
  ud1(:,m)=clati*ud1(:,m)
  ud2(:,m)=clati*ud2(:,m)
enddo
 !clati = 1/r, where r = cos(lat)

!>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>
 !Iteratively solve for h, u & v in both layers:

 !Energy norm error (must be > tole to start):
enorm=one
do while (enorm > tole)
   !Save previous fields to be able to compute error below:
  h1o=h1
  h2o=h2
  u1o=u1
  u2o=u2
  v1o=v1
  v2o=v2

   !Compute relative vorticity (now guaranteed to have zero average):
  do i=1,nt
    z1(:,i)=q1(:,i)*(one+h1(:,i))-cof
    z2(:,i)=q2(:,i)*(one+h2(:,i))-cof
  enddo

   !-------------------------------------------------------------
   !Complete calculation of zonal and meridional velocity, u & v,
   !and set up rhs for inversion of dimensionless height anomaly:

   !::::::::::::::::::::::::::::::::::::::::::::::::::::::
   !Layer 1:
  
   !Convert the relative vorticity to semi-spectral space:
  call forfft(ng,nt,z1,trig,factors) 

   !Convert the relative vorticity to semi-spectral space and de-alias:
!  call dealias(z1)
   !*** makes no difference  

   !Invert Laplace's operator on relative vorticity:
  call laplinv(z1,wka,wkb)
   !Here the streamfunction is wka while d(wka)/dlat = wkb.

   !Compute d(wka)/dlon = wkc:
  call deriv(ng,nt,rk,wka,wkc)

   !Convert h1 to semi-spectral space:
  call forfft(ng,nt,h1,trig,factors)

   !DGD
   !Replace u1 by its exact form:
  u1 = u1i
  call forfft(ng,nt,u1,trig,factors)
   !Use exact h1 on rhs below:
  wka=h1i
  call forfft(ng,nt,wka,trig,factors)
   !DGD

  do m=1,nt
    !DGD
    !u1(:,m)=ud1(:,m)-wkb(:,m)
    !DGD
    v1(:,m)=vd1(:,m)+clati*wkc(:,m)
    !DGD
    !h1(:,m)=gs1(:,m)+bet*u1(:,m)-cof*(z1(:,m)-cof*h1(:,m))
    h1(:,m)=gs1(:,m)+bet*u1(:,m)-cof*(z1(:,m)-cof*wka(:,m))
    !DGD
  enddo
   !All the terms in this loop are semi-spectral. Note, we will solve
   !f^2*h_1 - Lap(c_1^2*h_1+(rho_2/rho_1)*c_2^2*h_2) = h1, which follows
   !from the definition of gamma_1.

   !::::::::::::::::::::::::::::::::::::::::::::::::::::::
   !Layer 2:

   !Convert the relative vorticity to semi-spectral space:
  call forfft(ng,nt,z2,trig,factors) 

   !Convert the relative vorticity to semi-spectral space and de-alias:
!  call dealias(z2)
   !*** makes no difference  
  
   !Invert Laplace's operator on relative vorticity:
  call laplinv(z2,wka,wkb)
   !Here the streamfunction is wka while d(wka)/dlat = wkb.

   !Compute d(wka)/dlon = wkc:
  call deriv(ng,nt,rk,wka,wkc)

   !Convert h2 to semi-spectral space:
  call forfft(ng,nt,h2,trig,factors)

   !DGD
   !Replace u2 by its exact form:
  u2 = u2i
  call forfft(ng,nt,u2,trig,factors)
   !Use exact h2 on rhs below:
  wka=h2i
  call forfft(ng,nt,wka,trig,factors)
   !DGD

  do m=1,nt
    !DGD
    !u2(:,m)=ud2(:,m)-wkb(:,m)
    !DGD
    v2(:,m)=vd2(:,m)+clati*wkc(:,m)
    !DGD
    !h2(:,m)=gs2(:,m)+bet*u2(:,m)-cof*(z2(:,m)-cof*h2(:,m))
    h2(:,m)=gs2(:,m)+bet*u2(:,m)-cof*(z2(:,m)-cof*wka(:,m))
    !DGD
  enddo
   !All the terms in this loop are semi-spectral. Note, we will solve
   !f^2*h_2 - Lap(c_1^2*h_1+c_2^2*h_2) = h2, which follows from
   !the definition of gamma_2.

   !-------------------------------------------------------------------
   !Solve for h1 & h2 in mode space, where the equations are decoupled.

   !Mode 1:
  wka=h1*vm11+h2*vm12
  call helm1(wka,h1m,wkb)
   !Solves f^2*h_1 - \tilde{c}_1^2*Lap(h_1) = wka, where h_1 is h for mode 1
   !The solution is stored in h1m.
  
   !Mode 2:
  wka=h1*vm21+h2*vm22
  call helm2(wka,h2m,wkb)
   !Solves f^2*h_2 - \tilde{c}_2^2*Lap(h_2) = wka, where h_2 is h for mode 2
   !The solution is stored in h2m.

   !Return h1 & h2 to layers as semi-spectral arrays, then physical ones:
  h1=h1m*vt11+h2m*vt12
  call revfft(ng,nt,h1,trig,factors) 
  h2=h1m*vt21+h2m*vt22
  call revfft(ng,nt,h2,trig,factors) 

   !Return semi-spectral velocity field to physical space:
  call revfft(ng,nt,u1,trig,factors)
  call revfft(ng,nt,u2,trig,factors)

  call revfft(ng,nt,v1,trig,factors)
  call revfft(ng,nt,v2,trig,factors)

   !Compute relative error (measured by the energy norm):
  wka=(u1-u1o)**2+(v1-v1o)**2+csq1*(h1-h1o)**2 &
       +mubar*((u2-u2o)**2+(v2-v2o)**2+csq2*(h2-h2o)**2)
  wkb=u1**2+v1**2+csq1*h1**2+mubar*(u2**2+v2**2+csq2*h2**2)
  enorm=average(wka)/(average(wkb)+small)
   !Small = 1.d-12 is added to avoid dividing by zero for a rest state

   !Employ relaxation to improve convergence:
  h1=wgt*h1+wgtc*h1o
  h2=wgt*h2+wgtc*h2o

  !DGD
  !u1=wgt*u1+wgtc*u1o
  !u2=wgt*u2+wgtc*u2o
  !DGD

  v1=wgt*v1+wgtc*v1o
  v2=wgt*v2+wgtc*v2o

  if (enorm > one) stop
enddo
!<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<
 !Passing this point, we have converged!

 !Return semi-spectral relative vorticity field to physical space:
call revfft(ng,nt,z1,trig,factors)
call revfft(ng,nt,z2,trig,factors)

wka = abs(h1-h1i)
wkb = abs(h1i)
write(*,*) ' Max abs relative error in h1 = ',maxval(wka)/maxval(wkb)

wka = abs(h2-h2i)
wkb = abs(h2i)
write(*,*) ' Max abs relative error in h2 = ',maxval(wka)/maxval(wkb)

wka = abs(u1-u1i)
wkb = abs(u1i)
write(*,*) ' Max abs relative error in u1 = ',maxval(wka)/maxval(wkb)

wka = abs(u2-u2i)
wkb = abs(u2i)
write(*,*) ' Max abs relative error in u2 = ',maxval(wka)/maxval(wkb)

wka = abs(v1-v1i)
wkb = abs(v1i)
write(*,*) ' Max abs relative error in v1 = ',maxval(wka)/maxval(wkb)

wka = abs(v2-v2i)
wkb = abs(v2i)
write(*,*) ' Max abs relative error in v2 = ',maxval(wka)/maxval(wkb)

wka = abs(z1-z1i)
wkb = abs(z1i)
write(*,*) ' Max abs relative error in z1 = ',maxval(wka)/maxval(wkb)

wka = abs(z2-z2i)
wkb = abs(z2i)
write(*,*) ' Max abs relative error in z2 = ',maxval(wka)/maxval(wkb)

!------------------------------------------------------------------
 !Save h:
open(11,file='hh_init.r8',form='unformatted', &
      access='direct',status='replace',recl=2*nbytes)
write(11,rec=1) zero,h1
write(11,rec=2) zero,h2
close(11)

 !Save u:
open(11,file='uu_init.r8',form='unformatted', &
      access='direct',status='replace',recl=2*nbytes)
write(11,rec=1) zero,u1
write(11,rec=2) zero,u2
close(11)

 !Save v:
open(11,file='vv_init.r8',form='unformatted', &
      access='direct',status='replace',recl=2*nbytes)
write(11,rec=1) zero,v1
write(11,rec=2) zero,v2
close(11)

 !Save z:
open(11,file='zz_init.r8',form='unformatted', &
      access='direct',status='replace',recl=2*nbytes)
write(11,rec=1) zero,z1
write(11,rec=2) zero,z2
close(11)

 ! End main program
end program checkinv
