!######################################################################
!  Tests the vertical mode projection.

!  Uses data in hh0_init.r8, generated by init/random_huv.f90
!######################################################################

program testproj

 !Import parameters:
use constants

implicit none

double precision:: h1(numLatGridPts,numLongGridPts),h1o(numLatGridPts,numLongGridPts)
double precision:: h2(numLatGridPts,numLongGridPts),h2o(numLatGridPts,numLongGridPts)
double precision:: wka(numLatGridPts,numLongGridPts),wkb(numLatGridPts,numLongGridPts)
double precision:: t

!----------------------------------------------------------------------
! Read in the test field:
open(11, file = 'hh0_init.r8', form = 'unformatted', &
      access = 'direct', status = 'old', recl = 2*nbytes)
read(11,rec=1) t, h1
read(11,rec=2) t, h2
close(11)

! Keep a copy for comparison below:
h1o = h1
h2o = h2

! Project onto modes (wka,wkb):
wka = h1*vm11+h2*vm12
wkb = h1*vm21+h2*vm22

! Project back onto layers:
h1 = wka*vt11+wkb*vt12
h2 = wka*vt21+wkb*vt22

! Compute errors:
wka = abs(h1-h1o)
write(*,*) ' Max abs error in h1 projection = ',maxval(wka)

wka = abs(h2-h2o)
write(*,*) ' Max abs error in h2 projection = ',maxval(wka)

end program testproj
